    az_I = 0.5*2*np.pi*f2*np.cos(2*np.pi*f2*t)

    fx_b = np.zeros(N); fy_b = np.zeros(N); fz_b = np.zeros(N)

    for i in range(N):
        a_I = np.array([ax_I[i], ay_I[i], az_I[i]])
        f_B = Rs[i].T @ (a_I - g_I_3d)
