#-- 1. Simulation parameters ----------------------------

dt = 0.1 #so that is our delta t
T = 20.0 # total time
t = np.arange(0, T+dt, dt) # this would be our time array

# we need to create a shape for this as well
N = len(t)

f1, f2, f3, f4 = 1.0, 0.5, 0.75, 0.35 #defining our frequencies [Hz]

# define gravity
g_I = np.array([0.0, 9.81])  # now we have all the variables defined

# make the gravity in 3d as well

g_I_3d = np.array([0.0, 0.0, 9.81])  # this is our gravity in the 3D (z positive)

#-- 2. 2-D simulation -----------------------------------

# Assumptions:
# Theta(t) is the IMU orientation angle measured from the inertial frame

# Steps:
# Let's start with computing the iMU position (x(t), z(t))
# Let's start with creating a function for the 2-d simulation
def simulate_2d():

# we need to compute the IMU position and the orientation of theta(t)

  vx = 0.2*np.sin(2*np.pi*f1*t)
  vz = 0.5 *np.sin(2*np.pi*f2*t)
  wy = 0.5*(1.0+np.sin(2*np.pi*f3*t))

# We need to integrate the position of these (we are going to need this later)
  x = np.zeros(N)
  z = np.zeros(N)

# now we need to create a loop that will go through all our data and fill out
  for i in range(1,N):
      x[i] = x[i-1] + vx[i-1]*dt
      z[i] = z[i-1] + vz[i-1]*dt

# so after creating the loop we can integrate the IMU orientation of theta
  theta = np.zeros(N)
  for i in range(1,N):
    theta[i] = theta[i-1] + wy[i-1]*dt

# we need to do our acceleration and the derivative of the velocity

  ax_I = 0.2*2*np.pi*f1*np.cos(2*np.pi*f1*t)
  az_I = 0.5*2*np.pi*f2*np.cos(2*np.pi*f2*t)

# now we need to transform the body into inertial

  a = np.cos(theta) # cos of theta
  b = np.sin(theta) # our sin of theta

  net_ax = ax_I - g_I[0] #so when our g_I is 0
  net_az = az_I - g_I[1] #we subtract the g=9.81 and the z_I is in the positive direct.

  fx_b = a*net_ax + b*net_az    # our x direction
  fz_b = -b*net_ax + a*net_az   # our z direction


  return dict(t=t, x=x, z=z, theta=theta, vx=vx, vz=vz,
              ax_I=ax_I, az_I=az_I, fx_b=fx_b, fz_b=fz_b, wy=wy)

